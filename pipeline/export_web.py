"""Export the question bank and summaries into the Next.js app (web/public/data, web/public/img)."""
import hashlib, json, os, shutil, sys

from site_meta import HERE, STAR, GROUPS, MOF_GROUPS, load_chapters, slim_questions

WEB = os.path.normpath(os.path.join(HERE, '..', 'web'))
DATA_DIR = os.path.join(WEB, 'public', 'data')
IMG_DIR = os.path.join(WEB, 'public', 'img')


def dump(name, obj):
    s = json.dumps(obj, ensure_ascii=False, separators=(',', ':'))
    with open(os.path.join(DATA_DIR, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)
    return s


def main():
    Q = json.load(open(os.path.join(HERE, 'questions.json'), encoding='utf-8'))
    used = json.load(open(os.path.join(HERE, 'used_imgs.json')))
    summ, chapters = load_chapters()
    Q = slim_questions(Q, {c['k'] for c in chapters})

    os.makedirs(DATA_DIR, exist_ok=True)
    if os.path.isdir(IMG_DIR):
        shutil.rmtree(IMG_DIR)
    os.makedirs(IMG_DIR)
    for n in used:
        shutil.copy2(os.path.join(HERE, 'imgs', n + '.webp'), os.path.join(IMG_DIR, n + '.webp'))
    for q in Q:
        for n in q.get('im', []):
            assert n in used, (q['id'], n)

    h = hashlib.sha1()
    for name, obj in (('meta.json', {'chapters': chapters, 'star': STAR, 'groups': GROUPS, 'mof_groups': MOF_GROUPS}),
                      ('sum.json', summ), ('q.json', Q)):
        h.update(dump(name, obj).encode('utf-8'))
    version = h.hexdigest()[:10]
    with open(os.path.join(WEB, 'lib', 'version.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f"// generated by pipeline/export_web.py — changes whenever the data changes\nexport const VERSION = '{version}';\n")
    print('exported', len(Q), 'questions,', len(used), 'images, version', version, '->', WEB)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main()
